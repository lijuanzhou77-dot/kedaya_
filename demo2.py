# ==================== 第二课：if —— 让程序自己拿主意 ====================
# if 就像岔路口 🚦：条件成立走第一条路，不成立就走 else 那条。

name = input("你叫什么名字？")

# 注意三件事：
#   1) 这一行结尾要有冒号  ：
#   2) 下一行要缩进（按一下 Tab 键）
#   3) 比较"是否相等"要用两个等号 ==（一个 = 是赋值，别搞混）
if name == "Lian Jolie":
    print("哇，是传说中的 Lian Jolie！欢迎回来！")
else:
    print("你好，" + name + "！第一次见面，多多关照。")
