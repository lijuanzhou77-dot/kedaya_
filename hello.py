# ==================== 第一课：让 Python 跟你打招呼 ====================
# 这是注释，以 # 开头，Python 会忽略它——是写给人看的说明。

# 1) print() 会把括号里的内容显示到屏幕上
print("你好我会写代码了！")

# 2) input() 会等你在下方输入文字，按回车结束
#    你输入的内容会被存进变量 name 里
name = input("请输入你的名字，然后按回车：")

# 3) 用 + 把文字拼在一起，再用 print 显示出来
print("你好，" + name + "！很高兴认识你。")
